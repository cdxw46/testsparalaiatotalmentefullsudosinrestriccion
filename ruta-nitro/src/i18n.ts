const DICTIONARIES: Record<Lang, Partial<Record<TranslationKey, string>>> = { es, en }

export function translate(lang: Lang, key: TranslationKey, vars?: Record<string, string | number>): string {
  const template = DICTIONARIES[lang][key] ?? es[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => String(vars[name] ?? match))
}
